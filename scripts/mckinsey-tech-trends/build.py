def norm(s):
    s = s.replace("­", "")
    s = re.sub(r"[\s\-‐‑–—]+", "", s)
    return s.lower()


def T(rank, label, section, quote, subject, note=None, conf="high"):
    return dict(rank=rank, label=label, section=section, quote=quote, subject=subject,
                kind="trend", confidence=conf, note=note)


def F(rank, label, section, quote, subject, target_year, metric=None, value=None, unit=None,
       horizon=None, note=None, conf="high"):
    return dict(rank=rank, label=label, section=section, quote=quote, subject=subject,
                horizon=horizon, target_year=target_year, metric=metric, value=value, unit=unit,
                kind="forecast", confidence=conf, note=note)


def inv(y, i, j, iy, jy):
    return f"Report states (past-year context, not a forecast): equity investment {iy}: {i}; job postings {jy}: {j}."


