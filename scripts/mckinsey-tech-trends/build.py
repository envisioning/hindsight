def main():
    bad = 0
    OUT.mkdir(parents=True, exist_ok=True)
    for ed, entries in E.items():
        txt = norm((HERE / TEXT[ed]).read_text(errors="ignore"))
        alt = norm((HERE / RAW2[ed]).read_text(errors="ignore")) if ed in RAW2 else ""
        rows = []
        for e in entries:
            q = e["quote"]
            assert len(q) <= 400, (ed, q)
            found = norm(q) in txt or norm(q) in alt
            if not found:
                bad += 1
                print(f"NOT VERBATIM {ed} [{e['label']}]: {q[:90]}")
            row = {k: v for k, v in e.items() if v is not None or k in ("rank", "section")}
            row["source_url"] = URL[ed]
            rows.append(row)
        m = META[ed]
        doc = {"edition": ed, "published": m["published"], "status": m["status"],
               "sources": [URL[ed], WAYBACK[ed]], "publisher": PUB, "series": SERIES, "title": m["title"],
               "trend_count": sum(1 for r in rows if r["kind"] == "trend"),
               "forecast_count": sum(1 for r in rows if r["kind"] == "forecast"),
               "notes": m["notes"], "entries": rows}
        (OUT / f"{ed}.json").write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")
        print(ed, len(rows), "entries", doc["trend_count"], "trends", doc["forecast_count"], "forecasts")
    print("not verbatim:", bad)


if __name__ == "__main__":
    main()
